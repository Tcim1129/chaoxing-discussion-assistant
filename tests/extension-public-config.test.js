const assert=require('node:assert/strict');
const {shareableConfig,importedConfig}=require('../extension/options.js');
const secretAddress=new URL('https://api.example.test/v1?token=private#private');secretAddress.username='name';secretAddress.password='password';
const keys={cx_discussion_api_key:'private-example',cx_discussion_api_key_map:{'https://old.example.test/v1':'private-example'},cx_discussion_recent_presets:['https://private.example.test/v1'],cx_discussion_model:'example-model',cx_discussion_base_url:secretAddress.href,cx_discussion_anonymous:true};
const exported=shareableConfig(keys);
const serialized=JSON.stringify(exported);
for(const value of ['private-example','password','private.example.test','token=','name:'])assert.ok(!serialized.includes(value),value);
assert.ok(!Object.hasOwn(exported,'cx_discussion_api_key'));
assert.ok(!Object.hasOwn(exported,'cx_discussion_api_key_map'));
assert.ok(!Object.hasOwn(exported,'cx_discussion_recent_presets'));
assert.equal(exported.cx_discussion_base_url,'https://api.example.test/v1');
const current={...keys,cx_discussion_base_url:'https://old.example.test/v1'};
const same=importedConfig({cx_discussion_base_url:current.cx_discussion_base_url,cx_discussion_model:'other-model'},current);
assert.equal(same.cx_discussion_api_key,'private-example','importing a key-free config must preserve this endpoint key');
const other=importedConfig({cx_discussion_base_url:'https://new.example.test/v1'},current);
assert.equal(other.cx_discussion_api_key,'','an old key cannot migrate to another endpoint');
assert.equal(other.cx_discussion_api_key_map['https://old.example.test/v1'],'private-example');
const explicit=importedConfig({cx_discussion_base_url:'https://new.example.test/v1',cx_discussion_api_key:'new-example'},current);
assert.equal(explicit.cx_discussion_api_key,'new-example','explicit credential import remains supported');
console.log('ok - shareable configuration excludes credentials and history; import preserves endpoint isolation');
